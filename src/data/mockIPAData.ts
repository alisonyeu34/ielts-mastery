export type PhonemeType =
  | "monophthong_long"
  | "monophthong_short"
  | "diphthong"
  | "consonant_voiced"
  | "consonant_voiceless";

export interface IPAPhoneme {
  id: string;
  symbol: string;
  type: "monophthong" | "diphthong" | "consonant" | PhonemeType;
  category?: "vowel" | "consonant";
  sampleWord: string;
  sampleWordIpa?: string;
  sampleWordMeaningVi?: string;
  vietnameseMeaning?: string;
  mouthGuide?: {
    lipShape: string;
    tonguePlacement: string;
    voicing: string;
    commonMistake?: string;
  };
  examples?: Array<{
    position: "initial" | "medial" | "final";
    word: string;
    ipa: string;
    meaningVi: string;
  }>;
  mouthPosition?: {
    lips: string;
    tongue: string;
    jaw: string;
    vocalCords: string;
  };
  commonMistakeVi?: string;
  isVoiced: boolean;
  exampleWord: string;
  vietnameseGuide: string;
  mouthShape: "rounded" | "spread" | "neutral";
  tongueHeight: "high" | "mid" | "low";
  tonguePosition: "front" | "central" | "back";
  commonSpellings: string[];
}

